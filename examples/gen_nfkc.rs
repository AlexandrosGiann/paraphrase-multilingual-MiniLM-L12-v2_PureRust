//! Build src/nfkc_data.rs (Unicode 17.0 normalization data for NFKC) from the UCD files in
//! tools/ucd/. Unicode 17 is the version of the ICU in Node 24 that produced the reference.
//!     cargo run --example gen_nfkc
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;

fn main() {
    let root = env!("CARGO_MANIFEST_DIR");
    let ucd = format!("{}/tools/ucd", root);
    let mut decomp: BTreeMap<u32, (bool, Vec<u32>)> = BTreeMap::new();
    let mut ccc: BTreeMap<u32, u32> = BTreeMap::new();
    for line in fs::read_to_string(format!("{}/UnicodeData.txt", ucd)).unwrap().lines() {
        let f: Vec<&str> = line.split(';').collect();
        if f.len() < 6 {
            continue;
        }
        let cp = u32::from_str_radix(f[0], 16).unwrap();
        let c: u32 = f[3].parse().unwrap();
        if c != 0 {
            ccc.insert(cp, c);
        }
        if !f[5].is_empty() {
            let mut parts: Vec<&str> = f[5].split(' ').collect();
            let compat = parts[0].starts_with('<');
            if compat {
                parts.remove(0);
            }
            decomp.insert(cp, (compat, parts.iter().map(|h| u32::from_str_radix(h, 16).unwrap()).collect()));
        }
    }
    let mut exclusion: BTreeSet<u32> = BTreeSet::new();
    for line in fs::read_to_string(format!("{}/DerivedNormalizationProps.txt", ucd)).unwrap().lines() {
        let line = line.split('#').next().unwrap();
        let mut it = line.split(';');
        let (range, prop) = match (it.next(), it.next()) {
            (Some(r), Some(p)) => (r.trim(), p.trim()),
            _ => continue,
        };
        if prop != "Full_Composition_Exclusion" {
            continue;
        }
        let (a, b) = match range.split_once("..") {
            Some((a, b)) => (u32::from_str_radix(a, 16).unwrap(), u32::from_str_radix(b, 16).unwrap()),
            None => {
                let a = u32::from_str_radix(range, 16).unwrap();
                (a, a)
            }
        };
        for c in a..=b {
            exclusion.insert(c);
        }
    }
    fn full(cp: u32, d: &BTreeMap<u32, (bool, Vec<u32>)>, out: &mut Vec<u32>) {
        match d.get(&cp) {
            Some((_, cps)) => {
                for &c in cps {
                    full(c, d, out);
                }
            }
            None => out.push(cp),
        }
    }
    let mut src = String::new();
    src.push_str("// Unicode 17.0 data for NFKC, generated by `cargo run --example gen_nfkc` from tools/ucd.\n// Do not edit.\n\n");
    src.push_str("/// Full compatibility decompositions: (code point, offset, length) into DECOMP_CPS, sorted.\n");
    let mut idx = String::new();
    let mut cps = String::new();
    let mut off = 0;
    let mut n = 0;
    for (&cp, _) in &decomp {
        let mut v = Vec::new();
        full(cp, &decomp, &mut v);
        write!(idx, "({:#x},{},{}),", cp, off, v.len()).unwrap();
        for c in &v {
            write!(cps, "{:#x},", c).unwrap();
        }
        off += v.len();
        n += 1;
        if n % 8 == 0 {
            idx.push('\n');
        }
        if n % 8 == 0 {
            cps.push('\n');
        }
    }
    writeln!(src, "pub static DECOMP: [(u32, u32, u32); {}] = [\n{}];\n", decomp.len(), idx).unwrap();
    writeln!(src, "pub static DECOMP_CPS: [u32; {}] = [\n{}];\n", off, cps).unwrap();
    // combining classes as runs (start, end inclusive, class)
    let mut runs: Vec<(u32, u32, u32)> = Vec::new();
    for (&cp, &c) in &ccc {
        match runs.last_mut() {
            Some(r) if r.1 + 1 == cp && r.2 == c => r.1 = cp,
            _ => runs.push((cp, cp, c)),
        }
    }
    let mut s = String::new();
    for (i, r) in runs.iter().enumerate() {
        write!(s, "({:#x},{:#x},{}),", r.0, r.1, r.2).unwrap();
        if i % 8 == 7 {
            s.push('\n');
        }
    }
    writeln!(src, "/// Canonical combining classes (non-zero), runs (first, last, class), sorted.\npub static CCC: [(u32, u32, u8); {}] = [\n{}];\n", runs.len(), s).unwrap();
    // primary composites
    let mut comp: Vec<(u32, u32, u32)> = Vec::new();
    for (&cp, (compat, d)) in &decomp {
        if !*compat && d.len() == 2 && !exclusion.contains(&cp) {
            comp.push((d[0], d[1], cp));
        }
    }
    comp.sort();
    let mut s = String::new();
    for (i, c) in comp.iter().enumerate() {
        write!(s, "({:#x},{:#x},{:#x}),", c.0, c.1, c.2).unwrap();
        if i % 8 == 7 {
            s.push('\n');
        }
    }
    writeln!(src, "/// Primary composites (first, second, composite), sorted.\npub static COMPOSE: [(u32, u32, u32); {}] = [\n{}];", comp.len(), s).unwrap();
    fs::write(format!("{}/src/nfkc_data.rs", root), src).unwrap();
    println!("decompositions {}, ccc runs {}, compositions {}", decomp.len(), runs.len(), comp.len());
}
